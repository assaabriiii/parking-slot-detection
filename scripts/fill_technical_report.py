def set_run_text(cell, text: str) -> None:
    ps = cell.paragraphs
    if not ps:
        cell.text = text
        return
    p = ps[0]
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ""
    else:
        p.add_run(text)
    for extra in ps[1:]:
        for r in extra.runs:
            r.text = ""


def para_text_replace(p, text: str) -> None:
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


def add_body_p(doc: Document, text: str, style: str = "Normal") -> None:
    p = doc.add_paragraph(style=style)
    run = p.add_run(text)
    run.font.size = Pt(14)
    return p


def add_h(doc: Document, text: str, level: int = 1) -> None:
    style = {1: "Heading 1", 2: "Heading 2", 3: "Heading 3"}[level]
    p = doc.add_paragraph(style=style)
    p.add_run(text)


def add_caption(doc: Document, text: str, kind: str) -> None:
    style = "TableTitle" if kind == "table" else "PicTitle"
    try:
        p = doc.add_paragraph(style=style)
    except KeyError:
        p = doc.add_paragraph(style="Normal")
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run(text)


def add_table(doc: Document, headers: list[str], rows: list[list[str]], caption: str) -> None:
    add_caption(doc, caption, "table")
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    try:
        table.style = "Table Grid"
    except KeyError:
        pass
    for i, h in enumerate(headers):
        table.rows[0].cells[i].text = h
    for ri, row in enumerate(rows, start=1):
        for ci, val in enumerate(row):
            table.rows[ri].cells[ci].text = val
    doc.add_paragraph()


def add_picture(doc: Document, path: Path, caption: str, width_cm: float = 14.0) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    try:
        p.style = "In Picture"
    except KeyError:
        pass
    run = p.add_run()
    run.add_picture(str(path), width=Cm(width_cm))
    add_caption(doc, caption, "pic")


def delete_from_first_heading1(doc: Document) -> None:
    body = doc.element.body
    children = list(body)
    start_idx = None
    for i, child in enumerate(children):
        if child.tag != qn("w:p"):
            continue
        texts = [t.text or "" for t in child.iter(qn("w:t"))]
        joined = "".join(texts).strip()
        pPr = child.find(qn("w:pPr"))
        style = ""
        if pPr is not None:
            ps = pPr.find(qn("w:pStyle"))
            if ps is not None:
                style = ps.get(qn("w:val")) or ""
        if joined == "معرفی" and "Heading" in style:
            start_idx = i
            break
    if start_idx is None:
        raise RuntimeError("Heading 1 'معرفی' not found")
    for child in children[start_idx:]:
        if child.tag == qn("w:sectPr"):
            continue
        body.remove(child)


